const SUPPORTED_LANGS = ['tr', 'en', 'de', 'fr', 'es', 'zh', 'ja', 'ru'];
const LANG_STORAGE_KEY = 'smartcale-lang';

function getInitialLanguage() {
  const saved = localStorage.getItem(LANG_STORAGE_KEY) || localStorage.getItem('smartscale-lang');
  if (saved && SUPPORTED_LANGS.includes(saved)) {
    return saved;
  }
  const browserLang = (navigator.language || '').toLowerCase().slice(0, 2);
  if (SUPPORTED_LANGS.includes(browserLang)) {
    return browserLang;
  }
  return 'tr';
}

function applyFlasherLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) {
    lang = 'tr';
  }

  document.documentElement.lang = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) {
    // Ignore storage quota or security errors
  }

  const t = FLASHER_TRANSLATIONS[lang] || FLASHER_TRANSLATIONS.en;

  // Replace textContent
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  // Replace innerHTML for formatted strings with markup
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key]) {
      el.innerHTML = t[key];
    }
  });

  // Replace input placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) {
      el.setAttribute('placeholder', t[key]);
    }
  });

  // Replace title / aria-label
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (t[key]) {
      el.setAttribute('title', t[key]);
      el.setAttribute('aria-label', t[key]);
    }
  });

  // Keep select dropdown in sync
  const select = document.getElementById('langSelect');
  if (select && select.value !== lang) {
    select.value = lang;
  }
}

if (typeof window !== 'undefined') {
  window.FLASHER_LANGUAGES = FLASHER_LANGUAGES;
  window.FLASHER_TRANSLATIONS = FLASHER_TRANSLATIONS;
  window.SUPPORTED_LANGS = SUPPORTED_LANGS;
  window.LANG_STORAGE_KEY = LANG_STORAGE_KEY;
  window.getInitialLanguage = getInitialLanguage;
  window.applyFlasherLanguage = applyFlasherLanguage;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    FLASHER_LANGUAGES,
    FLASHER_TRANSLATIONS,
    SUPPORTED_LANGS,
    LANG_STORAGE_KEY,
    getInitialLanguage,
    applyFlasherLanguage,
  };
}
