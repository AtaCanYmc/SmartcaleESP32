export const getInitialLanguage = (): Language => {
  const supported: Language[] = ['tr', 'en', 'de', 'fr', 'es', 'zh', 'ja', 'ru'];
  const saved = localStorage.getItem('smartcale-lang') || localStorage.getItem('smartscale-lang');
  if (saved && supported.includes(saved as Language)) {
    return saved as Language;
  }
  const browserLang = (navigator.language || '').toLowerCase().slice(0, 2);
  if (supported.includes(browserLang as Language)) {
    return browserLang as Language;
  }
  return 'tr';
};
